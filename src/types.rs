//! Core handshake types between `tpt-statera` and `tpt-portus` (DESIGN.md §4).
//!
//! The `#[telos::verify]` contract annotations from the design are omitted here:
//! `tpt-telos` is an external dependency and is not available in this repository.

use std::fmt;

use serde::{Deserialize, Serialize};
use uuid::Uuid;

/// Chain identity as a tagged enum (DESIGN.md §4.2). A flat numeric id cannot
/// distinguish Cosmos zones or represent Bitcoin.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum ChainId {
    /// EVM chain identified by its EIP-155 chain id (e.g. 1 = Ethereum mainnet).
    Evm {
        eip155_id: u64,
    },
    /// Cosmos zone identified by its IBC chain id string (e.g. "osmosis-1").
    Cosmos {
        chain_id: String,
    },
    Solana {
        cluster: SolanaCluster,
    },
    Bitcoin {
        network: BitcoinNetwork,
    },
}

impl fmt::Display for ChainId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ChainId::Evm { eip155_id } => write!(f, "evm:{eip155_id}"),
            ChainId::Cosmos { chain_id } => write!(f, "cosmos:{chain_id}"),
            ChainId::Solana { cluster } => write!(f, "solana:{cluster:?}"),
            ChainId::Bitcoin { network } => write!(f, "bitcoin:{network:?}"),
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum SolanaCluster {
    Mainnet,
    Testnet,
    Devnet,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum BitcoinNetwork {
    Mainnet,
    Testnet,
    Signet,
}

/// Token descriptor (DESIGN.md §4.2.1). `symbol` is display-only and must not be
/// used for equality checks.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AssetDescriptor {
    pub symbol: String,
    pub source_contract: Vec<u8>,
    pub destination_contract: Vec<u8>,
    pub source_decimals: u8,
    pub destination_decimals: u8,
}

/// Outbound plan generated by `tpt-statera` (DESIGN.md §4.2). Immutable once signed.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct IntentExecutionPlan {
    pub intent_id: Uuid,
    pub source_chain: ChainId,
    pub destination_chain: ChainId,
    pub asset: AssetDescriptor,
    /// Denominated in `asset.source_decimals` units on the source chain.
    pub amount: u64,
    pub recipient_address: Vec<u8>,
    pub timeout_block_height: u64,
    /// Fetched from Portus, not hard-coded by Statera (DESIGN.md §4.5).
    pub dispute_window_secs: u64,
    pub fee_budget: u64,
    pub cryptographic_proof: Vec<u8>,
    pub created_at: u64,
    pub protocol_version: u16,
    /// Proves the source-chain lock is past reorg risk (DESIGN.md §4.6).
    pub source_finality_proof: Vec<u8>,
}

/// Inbound receipt generated by `tpt-portus` (DESIGN.md §4.3).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ExecutionReceipt {
    pub intent_id: Uuid,
    pub destination_chain: ChainId,
    pub status: ExecutionStatus,
    pub chain_proof: Vec<u8>,
    pub executed_at_block: u64,
    pub portus_signature: Vec<u8>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum ExecutionStatus {
    /// Accepted, not yet claimed (matches proto PENDING).
    Pending,
    /// Claimed by a relayer (matches proto IN_FLIGHT).
    InFlight,
    Success {
        tx_hash: String,
        block_number: u64,
    },
    Failed {
        error_code: u32,
        revert_reason: String,
    },
    Timeout {
        current_block: u64,
        timeout_block: u64,
    },
    DisputeWindowOpen {
        closes_at_secs: u64,
    },
    /// ROLLED_BACK marker written (matches proto ROLLED_BACK).
    RolledBack,
}
